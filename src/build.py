"""Builds i18n.js from src/i18n/keys.txt and src/i18n/<language>.txt.
Each language file has the translation on the SAME line number as the English text in keys.txt.
An empty line means: use Google automatic translation for that text.
Use (from the repo folder):  python3 src/build.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
I18N = os.path.join(HERE, 'i18n')

def read_lines(path):
    with open(path, encoding='utf-8') as f:
        return f.read().rstrip('\n').split('\n')

keys = read_lines(os.path.join(I18N, 'keys.txt'))
dic = {}
errors = 0
for name in sorted(os.listdir(I18N)):
    if not name.endswith('.txt') or name == 'keys.txt':
        continue
    lang = name[:-4]
    lines = read_lines(os.path.join(I18N, name))
    if len(lines) != len(keys):
        print(f'ERROR {name}: {len(lines)} lines, keys.txt has {len(keys)}')
        errors += 1
        continue
    d = {k: v.strip() for k, v in zip(keys, lines) if v.strip()}
    dic[lang] = d
    print(f'{lang}: {len(d)} texts')

if errors:
    sys.exit(1)

js = '/* Generated by src/build.py. Do not edit by hand: edit src/i18n/*.txt */\nwindow.HK_DICT=' + \
     json.dumps(dic, ensure_ascii=False, separators=(',', ':')) + ';\n'
with open(os.path.join(ROOT, 'i18n.js'), 'w', encoding='utf-8') as f:
    f.write(js)
print('i18n.js OK')
